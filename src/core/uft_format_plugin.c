/* MF-445: was 32. The tree defines 137 plugins, so uft_register_all_formats()
 * would have filled the table and then returned UFT_ERROR_BUFFER_TOO_SMALL for
 * the remaining 105 — the third gate in a row that silently capped the registry
 * far below the plugin count (the other two: duplicate-check on .format, and
 * having no caller at all; see ARCH-9).
 *
 * MF-446: 128 was still too small. The count is not 88 but 137 — 88 written out
 * and 49 generated by the DSK_PLUGIN() macro in src/formats/dsk_generic/, which
 * the MF-445 gate could not see because it only matched written-out definitions.
 * A gate that undercounts is worse than none: it reported "fits" while nine
 * plugins would have been refused. The gate counts the macro now too.
 *
 * 192 leaves room for ~55 more. */
#define MAX_FORMAT_PLUGINS 192

static const uft_format_plugin_t* g_format_plugins[MAX_FORMAT_PLUGINS] = {0};
static size_t g_format_plugin_count = 0;

// ============================================================================
// Registration
// ============================================================================

uft_error_t uft_register_format_plugin(const uft_format_plugin_t* plugin) {
    if (!plugin) return UFT_ERROR_NULL_POINTER;
    if (!plugin->name) return UFT_ERROR_INVALID_ARG;

    /* UFT-004 (v4.1.5-hardening) ABI gate.
     * api_version == 0 ⇒ legacy plugin (pre-v4.1.5), accepted with stderr
     *                    warning so the gap is visible in the build log.
     * api_version > UFT_PLUGIN_API_VERSION ⇒ plugin compiled against a newer
     *                    header than the running host. Reject — silent
     *                    layout drift is exactly the bomb we want to avoid.
     */
    if (plugin->api_version > UFT_PLUGIN_API_VERSION) {
        fprintf(stderr,
                "[UFT] reject plugin '%s': api_version=%u > host=%u (rebuild plugin against current headers)\n",
                plugin->name, plugin->api_version, UFT_PLUGIN_API_VERSION);
        return UFT_ERROR_PLUGIN_LOAD;
    }
    if (plugin->api_version == 0u) {
        /* One-shot warning — 80 plugins registering at startup would
         * otherwise spam stderr with the same message 80 times. The
         * actual migration trigger is the v5.0 reject; this is just
         * a developer reminder. */
        static int s_legacy_warned = 0;
        if (!s_legacy_warned) {
            s_legacy_warned = 1;
            fprintf(stderr,
                    "[UFT] note: one or more plugins have api_version=0 "
                    "(legacy). First seen: '%s'. Plugins must set "
                    ".api_version = UFT_PLUGIN_API_VERSION before v5.0.\n",
                    plugin->name);
        }
    }

    /* Duplikate prüfen — auf .name, nicht auf .format (MF-444).
     *
     * This test used to read `g_format_plugins[i]->format == plugin->format`.
     * 131 of the 137 plugins in the tree declare `.format = UFT_FORMAT_DSK`,
     * because that enum names a container class ("a sector image"), not a
     * format. The registry therefore accepted the first DSK plugin and rejected
     * the other 130, silently, with the same error code used for a plugin that
     * is genuinely broken. Registration could never hold more than 7 of 137.
     *
     * That is why nothing in the tree calls uft_register_all_formats(): every
     * consumer grew around the registry by linking plugin symbols directly.
     *
     * `.name` is unique across all 137 and is what identifies a plugin. Two
     * plugins sharing a container id is normal and must not be an error. */
    for (size_t i = 0; i < g_format_plugin_count; i++) {
        if (g_format_plugins[i]->name && plugin->name &&
            strcmp(g_format_plugins[i]->name, plugin->name) == 0) {
            return UFT_ERROR_PLUGIN_LOAD;
        }
    }
    
    if (g_format_plugin_count >= MAX_FORMAT_PLUGINS) {
        fprintf(stderr,
                "[UFT] reject plugin '%s': registry full at %d entries - raise "
                "MAX_FORMAT_PLUGINS in src/core/uft_format_plugin.c\n",
                plugin->name, MAX_FORMAT_PLUGINS);
        return UFT_ERROR_BUFFER_TOO_SMALL;
    }
    
    // Plugin initialisieren
    if (plugin->init) {
        uft_error_t err = plugin->init();
        if (UFT_FAILED(err)) {
            return err;
        }
    }
    
    g_format_plugins[g_format_plugin_count++] = plugin;
    
    return UFT_OK;
}

uft_error_t uft_unregister_format_plugin(uft_format_t format) {
    for (size_t i = 0; i < g_format_plugin_count; i++) {
        if (g_format_plugins[i]->format == format) {
            // Plugin shutdown
            if (g_format_plugins[i]->shutdown) {
                g_format_plugins[i]->shutdown();
            }
            
            // Lücke schließen
            for (size_t j = i; j + 1 < g_format_plugin_count; j++) {
                g_format_plugins[j] = g_format_plugins[j + 1];
            }
            g_format_plugin_count--;
            g_format_plugins[g_format_plugin_count] = NULL;
            
            return UFT_OK;
        }
    }
    
    return UFT_ERROR_PLUGIN_NOT_FOUND;
}

