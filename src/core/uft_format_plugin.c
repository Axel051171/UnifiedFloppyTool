/* First plugin declaring this container id.
 *
 * MF-444: with 131 plugins on UFT_FORMAT_DSK this is a first-match, not an
 * identification — the answer depends on registration order, and it is wrong
 * for 130 of the 131 whenever the caller meant a specific format. The callers in
 * src/core/uft_disk_*.c and uft_format_verify.c pass a uft_format_t and cannot
 * express more, so the ambiguity is theirs to lose, not this function's to
 * hide: it is stated here and tracked as ARCH-9 in docs/KNOWN_ISSUES.md.
 * Callers that know which plugin they want should use
 * uft_get_format_plugin_by_name(). */
const uft_format_plugin_t* uft_get_format_plugin(uft_format_t format) {
    for (size_t i = 0; i < g_format_plugin_count; i++) {
        if (g_format_plugins[i]->format == format) {
            return g_format_plugins[i];
        }
    }
    return NULL;
}

/* Does this plugin claim `ext` (without the dot)?
 *
 * MF-445: replaces a strtok() loop over a 256-byte stack copy. strtok keeps its
 * cursor in static storage, so two threads walking the plugin list at once
 * interleaved each other's tokenisation — and the copy silently truncated any
 * extension list longer than 255 characters. This walks the string in place:
 * no copy, no truncation, no shared cursor. Separators are ';', ',' and
 * whitespace; a leading dot on either side is tolerated. */
static bool plugin_claims_extension(const uft_format_plugin_t* plugin,
                                    const char* ext) {
    if (!plugin || !plugin->extensions || !ext || !*ext) return false;
    if (*ext == '.') ext++;
    size_t want = strlen(ext);
    if (want == 0) return false;

    for (const char* s = plugin->extensions; *s; ) {
        while (*s == ';' || *s == ',' || *s == ' ' || *s == '	' || *s == '.') s++;
        if (!*s) break;
        const char* start = s;
        while (*s && *s != ';' && *s != ',' && *s != ' ' && *s != '	') s++;
        size_t len = (size_t)(s - start);
        if (len == want) {
            size_t i = 0;
            while (i < len &&
                   tolower((unsigned char)start[i]) == tolower((unsigned char)ext[i]))
                i++;
            if (i == len) return true;
        }
    }
    return false;
}

/* MF-445: resolve a target plugin without guessing.
 *
 * A uft_format_t alone cannot name a plugin — 131 of 137 carry UFT_FORMAT_DSK.
 * The ladder, each rung refusing to invent what it does not know:
 *
 *   1. the id, if exactly one registered plugin carries it
 *   2. the extension of path_hint, among the plugins carrying that id
 *   3. nothing
 *
 * Rung 2 deserves a word, because uft_smart_open() just LOST its extension
 * fallback (MF-444) and this looks like the same move reversed. It is not. In
 * smart_open the name of an existing file was used to make a claim about the
 * bytes inside it — evidence it is not. Here the file does not exist yet and
 * the caller is choosing what to write: "out.d81" is a statement of intent, and
 * intent is exactly what a target format is.
 *
 * candidates_out, when given, receives how many plugins carried the id — so a
 * caller that gets NULL can say "12 plugins claim this id" instead of the
 * indistinguishable "unsupported". */
const uft_format_plugin_t* uft_resolve_format_plugin(uft_format_t format,
                                                     const char* path_hint,
                                                     size_t* candidates_out) {
    size_t n = uft_count_format_plugins_for(format);
    if (candidates_out) *candidates_out = n;
    if (n == 0) return NULL;
    if (n == 1) return uft_get_format_plugin(format);

    if (!path_hint) return NULL;
    const char* dot = strrchr(path_hint, '.');
    if (!dot || !dot[1]) return NULL;

    const uft_format_plugin_t* hit = NULL;
    for (size_t i = 0; i < g_format_plugin_count; i++) {
        const uft_format_plugin_t* pl = g_format_plugins[i];
        if (!pl || pl->format != format || !pl->extensions) continue;
        if (!plugin_claims_extension(pl, dot + 1)) continue;
        if (hit) return NULL;          /* two plugins claim it: still a guess */
        hit = pl;
    }
    return hit;
}

const uft_format_plugin_t* uft_disk_plugin(const uft_disk_t* disk) {
    if (!disk) return NULL;
    if (disk->plugin) return disk->plugin;

    /* No plugin recorded: the disk predates the field or was assembled by
     * hand. Resolve from the container id only when it can identify exactly
     * one plugin — a first match out of 82 would be a guess, and the caller
     * uses the result to touch plugin_data. */
    if (uft_count_format_plugins_for(disk->format) != 1) return NULL;
    return uft_get_format_plugin(disk->format);
}

size_t uft_count_format_plugins_for(uft_format_t format) {
    size_t n = 0;
    for (size_t i = 0; i < g_format_plugin_count; i++)
        if (g_format_plugins[i]->format == format) n++;
    return n;
}

const uft_format_plugin_t* uft_get_format_plugin_by_name(const char* name) {
    if (!name) return NULL;
    for (size_t i = 0; i < g_format_plugin_count; i++) {
        if (g_format_plugins[i]->name &&
            strcmp(g_format_plugins[i]->name, name) == 0) {
            return g_format_plugins[i];
        }
    }
    return NULL;
}

/* ============================================================================
 * Plugin Probing — Buffer and File
 * ============================================================================ */

/* MF-448 (ARCH-13): one pass, and it keeps what the old loop threw away.
 *
 * The winner is unchanged and still deterministic — strict `>` means the first
 * registered plugin keeps a tie, exactly as before, so no caller sees a
 * different format than yesterday. What is new is that the tie is now
 * countable. On atrcopy_dos2sd.xfd four plugins answer 40; the old return value
 * could not distinguish that from a lone 40, and every consumer printed the
 * winner as though it had been identified. */
size_t uft_probe_buffer_ranked(const uint8_t *data, size_t size,
                               size_t file_size, uft_probe_ranking_t *result) {
    uft_probe_ranking_t r;
    memset(&r, 0, sizeof(r));

    if (data && size > 0) {
        for (size_t i = 0; i < g_format_plugin_count; i++) {
            const uft_format_plugin_t *p = g_format_plugins[i];
            if (!p || !p->probe) continue;
            int conf = 0;
            if (!p->probe(data, size, file_size, &conf)) continue;

            r.claimants++;
            if (conf > r.confidence) {
                /* the previous best becomes the runner-up */
                r.runner_up = r.winner;
                r.runner_up_confidence = r.confidence;
                r.winner = p;
                r.confidence = conf;
                r.tied = 1;
            } else if (conf == r.confidence && r.winner) {
                r.tied++;                       /* as good as the winner */
            } else if (conf > r.runner_up_confidence) {
                r.runner_up = p;
                r.runner_up_confidence = conf;
            }
        }
    }

    if (result) *result = r;
    return r.claimants;
}

size_t uft_probe_file_ranked(const char *path, uft_probe_ranking_t *result) {
    if (result) memset(result, 0, sizeof(*result));
    if (!path) return 0;

    FILE *f = fopen(path, "rb");
    if (!f) return 0;
    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return 0; }
    long fs = ftell(f);
    if (fs < 0) { fclose(f); return 0; }
    if (fseek(f, 0, SEEK_SET) != 0) { fclose(f); return 0; }

    size_t probe_size = ((size_t)fs < UFT_PROBE_BUFFER_SIZE)
                            ? (size_t)fs : UFT_PROBE_BUFFER_SIZE;
    uint8_t *buf = malloc(probe_size);
    if (!buf) { fclose(f); return 0; }
    if (fread(buf, 1, probe_size, f) != probe_size) {
        free(buf); fclose(f); return 0;
    }
    fclose(f);

    size_t n = uft_probe_buffer_ranked(buf, probe_size, (size_t)fs, result);
    free(buf);
    return n;
}

const uft_format_plugin_t* uft_probe_buffer_format(const uint8_t *data,
                                                     size_t size,
                                                     size_t file_size) {
    uft_probe_ranking_t r;
    uft_probe_buffer_ranked(data, size, file_size, &r);
    return r.winner;
}

const uft_format_plugin_t* uft_probe_file_format(const char *path) {
    if (!path) return NULL;
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;

    if (fseek(f, 0, SEEK_END) != 0) { fclose(f); return NULL; }
    long fs = ftell(f);
    if (fs < 0) { fclose(f); return NULL; }
    if (fseek(f, 0, SEEK_SET) != 0) { fclose(f); return NULL; }

    size_t probe_size = ((size_t)fs < UFT_PROBE_BUFFER_SIZE)
                            ? (size_t)fs : UFT_PROBE_BUFFER_SIZE;
    uint8_t *buf = malloc(probe_size);
    if (!buf) { fclose(f); return NULL; }

    if (fread(buf, 1, probe_size, f) != probe_size) {
        free(buf); fclose(f); return NULL;
    }
    fclose(f);

    uft_probe_ranking_t r;
    uft_probe_buffer_ranked(buf, probe_size, (size_t)fs, &r);
    free(buf);
    return r.winner;
}

const uft_format_plugin_t* uft_find_format_plugin_by_extension(const char* ext) {
    if (!ext || !*ext) return NULL;
    
    // Punkt überspringen
    if (*ext == '.') ext++;
    
    for (size_t i = 0; i < g_format_plugin_count; i++) {
        if (plugin_claims_extension(g_format_plugins[i], ext))
            return g_format_plugins[i];
    }

    /* First match. 13 of the 104 extensions in the tree are claimed by more
     * than one plugin (".dsk" by 18), so for those the answer above is a pick,
     * not an identification — callers that must be right use
     * uft_resolve_format_plugin() or uft_get_format_plugin_by_name(). */
    return NULL;
}

/* uft_find_format_plugin_for_file() stood here until MF-449.
 *
 * It was the THIRD implementation of "probe a file": its own 4096-byte stack
 * buffer, its own copy of the best-confidence loop, and — after the loop — a
 * fallback that guessed the format from the file extension, the same guess
 * uft_smart_open() lost in MF-444 for claiming something about the content
 * from something that is not the content.
 *
 * It had no caller anywhere in the tree. Removed rather than kept in step with
 * uft_probe_file_ranked(), because three copies of one decision is how the
 * buffer sizes drifted apart in the first place (ARCH-15). */

size_t uft_registered_format_plugin_count(void) {
    return g_format_plugin_count;
}

size_t uft_list_format_plugins(const uft_format_plugin_t** plugins, size_t max) {
    if (!plugins || max == 0) return 0;
    
    size_t count = 0;
    for (size_t i = 0; i < g_format_plugin_count && count < max; i++) {
        plugins[count++] = g_format_plugins[i];
    }
    
    return count;
}

